"""
The committed JSON Schemas and the mapping document cannot drift from the
models.

Work order 03 requirement 9 makes the exported schemas a graded deliverable
that also feeds the API collection, which means a stale file is worse than
no file: a consumer validating against it would be checking a contract the
code no longer has. So the artefacts are generated by
`agent/scripts/export_w2_schemas.py` and this asserts the committed copies
match what the models produce now.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

import pytest

AGENT_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = AGENT_ROOT.parent
SCRIPT = AGENT_ROOT / "scripts" / "export_w2_schemas.py"


def _load_exporter() -> Any:
    spec = importlib.util.spec_from_file_location("export_w2_schemas", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


exporter = _load_exporter()


def test_the_committed_artefacts_are_current() -> None:
    drifted = [path.relative_to(REPO_ROOT).as_posix() for path in exporter.stale()]
    assert drifted == [], "regenerate with: cd agent && python scripts/export_w2_schemas.py"


@pytest.mark.parametrize("name", ["lab_pdf", "intake_form"])
def test_each_schema_is_valid_json_and_self_describing(name: str) -> None:
    path = REPO_ROOT / "docs" / "w2" / "schemas" / f"{name}.schema.json"
    document = json.loads(path.read_text(encoding="utf-8"))
    assert document["$schema"] == "https://json-schema.org/draft/2020-12/schema"
    assert f"w2-contracts/{name}/1.0.0" in document["$id"]
    assert document["type"] == "object"
    assert document["additionalProperties"] is False


@pytest.mark.parametrize("name", ["lab_pdf", "intake_form"])
def test_the_shared_contract_pieces_appear_in_both(name: str) -> None:
    """The two documents describe one contract, not two overlapping ones."""
    path = REPO_ROOT / "docs" / "w2" / "schemas" / f"{name}.schema.json"
    definitions = json.loads(path.read_text(encoding="utf-8"))["$defs"]
    for shared in ("Citation", "BBox", "FieldStatus", "SourceType", "SourceDocument"):
        assert shared in definitions


def test_generic_definitions_are_named_readably() -> None:
    """A published schema other tools read cannot have a `$defs` key built
    from a Python repr."""
    path = REPO_ROOT / "docs" / "w2" / "schemas" / "lab_pdf.schema.json"
    definitions = json.loads(path.read_text(encoding="utf-8"))["$defs"]
    extracted = sorted(key for key in definitions if key.startswith("ExtractedField"))
    assert extracted == [
        "ExtractedField_AbnormalFlag_",
        "ExtractedField_LabValue_",
        "ExtractedField_ReferenceRange_",
        "ExtractedField_date_",
        "ExtractedField_datetime_",
        "ExtractedField_str_",
    ]
    assert all(len(key) < 60 for key in definitions)


def test_the_lab_value_union_is_discriminated_in_the_published_schema() -> None:
    path = REPO_ROOT / "docs" / "w2" / "schemas" / "lab_pdf.schema.json"
    lab_value = json.loads(path.read_text(encoding="utf-8"))["$defs"]["LabValue"]
    assert lab_value["discriminator"]["propertyName"] == "kind"
    assert set(lab_value["discriminator"]["mapping"]) == {"numeric", "qualitative"}


def test_the_mapping_document_lists_both_directions() -> None:
    text = (REPO_ROOT / "docs" / "w2" / "factory-field-mapping.md").read_text(encoding="utf-8")
    assert "## Factory paths with no schema field" in text
    assert "## Schema fields with no factory path" in text
    assert "`results.<panel>.<test>.value`" in text
    assert "`intake_form.medications[].route`" in text
    assert "never from `value`" in text


def test_the_exporter_check_mode_agrees_with_the_files_on_disk() -> None:
    argv = sys.argv
    try:
        sys.argv = ["export_w2_schemas.py", "--check"]
        assert exporter.main() == 0
    finally:
        sys.argv = argv
