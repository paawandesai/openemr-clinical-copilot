#!/usr/bin/env python3
"""
Export the Week 2 document schemas to docs/w2/ — JSON Schema plus the
doc-factory mapping table.

    cd agent
    python scripts/export_w2_schemas.py            # write the files
    python scripts/export_w2_schemas.py --check    # fail if they are stale

Three files, all generated, none hand-edited:

    docs/w2/schemas/lab_pdf.schema.json
    docs/w2/schemas/intake_form.schema.json
    docs/w2/schemas/lab_writeback_request.schema.json
    docs/w2/schemas/lab_writeback_response.schema.json
    docs/w2/factory-field-mapping.md

The JSON Schemas are in *validation* mode — what an instance is checked
against — because that is what the API collection and any non-Python
consumer needs. `$defs` carries the shared pieces (`Citation`, `BBox`, the
`ExtractedField` instantiations) so the two files describe one contract
rather than two overlapping ones.

`--check` is what tests/test_w2_json_schema_export.py runs. The point of
generating rather than writing these is that the committed artefact cannot
drift from the models: a schema change that is not exported fails the test.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

AGENT_ROOT = Path(__file__).resolve().parents[1]
if str(AGENT_ROOT) not in sys.path:
    sys.path.insert(0, str(AGENT_ROOT))

from app.models.w2.factory_mapping import (  # noqa: E402
    FIELD_PATH_RULES,
    GROUND_TRUTH_ATTRIBUTES_NOT_CARRIED,
    SCHEMA_FIELDS_WITHOUT_FACTORY_PATH,
    SUPPORTED_GROUND_TRUTH_SCHEMA_VERSION,
    UNMAPPED_FACTORY_PATHS,
)
from app.models.w2.intake_form import (  # noqa: E402
    INTAKE_FORM_SCHEMA_VERSION,
    IntakeFormExtraction,
)
from app.models.w2.lab_pdf import LAB_PDF_SCHEMA_VERSION, LabPdfExtraction  # noqa: E402
from app.models.w2.writeback import (  # noqa: E402
    LAB_WRITEBACK_REQUEST_SCHEMA_VERSION,
    LAB_WRITEBACK_RESPONSE_SCHEMA_VERSION,
    LabWriteBackRequest,
    LabWriteBackResponse,
)

REPO_ROOT = AGENT_ROOT.parent
SCHEMA_DIR = REPO_ROOT / "docs" / "w2" / "schemas"
MAPPING_DOC = REPO_ROOT / "docs" / "w2" / "factory-field-mapping.md"

GENERATED_BY = "agent/scripts/export_w2_schemas.py"


def _schema(model: type, schema_id: str, title: str) -> str:
    document = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": schema_id,
        "title": title,
        **model.model_json_schema(mode="validation"),
    }
    return json.dumps(document, indent=2, sort_keys=False) + "\n"


def lab_pdf_schema() -> str:
    return _schema(
        LabPdfExtraction,
        f"https://clinical-copilot.invalid/schemas/{LAB_PDF_SCHEMA_VERSION}",
        "Lab PDF extraction",
    )


def intake_form_schema() -> str:
    return _schema(
        IntakeFormExtraction,
        f"https://clinical-copilot.invalid/schemas/{INTAKE_FORM_SCHEMA_VERSION}",
        "Intake form extraction",
    )


def lab_writeback_request_schema() -> str:
    return _schema(
        LabWriteBackRequest,
        f"https://clinical-copilot.invalid/schemas/{LAB_WRITEBACK_REQUEST_SCHEMA_VERSION}",
        "Lab write-back request",
    )


def lab_writeback_response_schema() -> str:
    return _schema(
        LabWriteBackResponse,
        f"https://clinical-copilot.invalid/schemas/{LAB_WRITEBACK_RESPONSE_SCHEMA_VERSION}",
        "Lab write-back response",
    )


def mapping_document() -> str:
    lines = [
        "# doc-factory ground truth -> Week 2 schema",
        "",
        f"**Generated by `{GENERATED_BY}`. Do not edit by hand.**",
        "",
        "Requirement 8 of work order 03: every ground-truth `field_path` the",
        "doc-factory emits maps to a schema field, and the schema fields that have",
        "no factory counterpart are listed too. The adapter is",
        "`agent/app/models/w2/factory_mapping.py`; the proof that all six committed",
        "samples convert is `agent/tests/test_w2_factory_ground_truth.py`.",
        "",
        f"Ground-truth format: `{SUPPORTED_GROUND_TRUTH_SCHEMA_VERSION}`.",
        "",
        "## What the adapter must not do",
        "",
        "A ground-truth `FieldRecord` carries both a `value` and a `rendered_text`.",
        "`rendered_text` is what is drawn on the page; `value` is the semantic value,",
        "and for `absent` and `illegible` fields it is **the chart truth the document",
        "fails to convey**. So `ExtractedField.value` is derived from `rendered_text`",
        "and never from `value` — copying `value` across would present chart truth as",
        "document content, breaking CLAUDE.md invariant 4 on exactly the cases the",
        "factory built to catch it. The chart truth comes back separately, in",
        "`GroundTruthConversion.chart_truth`.",
        "",
        "## Status mapping",
        "",
        "| ground truth `status` | schema `FieldStatus` | value | citation |",
        "|---|---|---|---|",
        "| `present` | `located` | the drawn text, parsed | document citation with bbox |",
        "| `absent` | `missing` | none | none |",
        "| `illegible` | `illegible` | none | document citation, bbox = the ink region |",
        "| — | `unlocated` | the drawn text | document citation without a bbox |",
        "",
        "`unlocated` has no ground-truth counterpart: it is not a property of a",
        "document but what the D3 locate step concludes at runtime when it cannot",
        "place a value the model read.",
        "",
        "## Rendering mapping",
        "",
        "Ground truth 0.2.0 declares, per text field, how `rendered_text` relates to",
        "`value`. Every value below is `located` — each one is genuinely on the page —",
        "and everything but `verbatim` also produces a `ChartTruthNote`.",
        "",
        "| `rendering` | what the schema does |",
        "|---|---|",
        "| `verbatim` | the value, no note |",
        "| `derived` | the drawn form is the value; the chart's wording goes to `chart_truth` |",
        "| `wrapped` | the joined lines are the value; `bbox` is the union of the line boxes |",
        "| `truncated` | the ellipsised text is the value; the full text is unrecoverable from the document and goes to `chart_truth` |",
        "",
        "## Field paths",
        "",
        "Placeholders: `<panel>`, `<test>`, `<i>` and `<condition>` stand for the part",
        "of the path that varies.",
        "",
        "| document | factory `field_path` | schema field | notes |",
        "|---|---|---|---|",
    ]
    for rule in FIELD_PATH_RULES:
        lines.append(
            f"| `{rule.doc_kind}` | `{rule.factory_path}` | `{rule.schema_path}` | "
            f"{rule.note or '—'} |"
        )

    lines += [
        "",
        "## Factory paths with no schema field",
        "",
    ]
    if UNMAPPED_FACTORY_PATHS:
        lines += [f"- `{path}`" for path in sorted(UNMAPPED_FACTORY_PATHS)]
    else:
        lines.append(
            "None. Every `field_path` in the six committed samples maps; the adapter "
            "reports anything it cannot place in `unmapped_field_paths`, and the test "
            "asserts that list is empty."
        )

    lines += [
        "",
        "## Schema fields with no factory path",
        "",
        "| schema field | why |",
        "|---|---|",
    ]
    for field, reason in SCHEMA_FIELDS_WITHOUT_FACTORY_PATH.items():
        lines.append(f"| `{field}` | {' '.join(reason.split())} |")

    lines += [
        "",
        "## Ground-truth record attributes the schema does not carry",
        "",
        "Per-field metadata rather than `field_path`s, so not part of the table",
        'above. Listed because "every field path maps" would otherwise read as',
        '"nothing is dropped", and these are dropped on purpose.',
        "",
        "| attribute | why |",
        "|---|---|",
    ]
    for attribute, reason in GROUND_TRUTH_ATTRIBUTES_NOT_CARRIED.items():
        lines.append(f"| `{attribute}` | {' '.join(reason.split())} |")
    lines.append("")
    return "\n".join(lines)


ARTEFACTS: dict[Path, str] = {}


def _artefacts() -> dict[Path, str]:
    if not ARTEFACTS:
        ARTEFACTS.update(
            {
                SCHEMA_DIR / "lab_pdf.schema.json": lab_pdf_schema(),
                SCHEMA_DIR / "intake_form.schema.json": intake_form_schema(),
                SCHEMA_DIR / "lab_writeback_request.schema.json": lab_writeback_request_schema(),
                SCHEMA_DIR / "lab_writeback_response.schema.json": lab_writeback_response_schema(),
                MAPPING_DOC: mapping_document(),
            }
        )
    return ARTEFACTS


def write() -> list[Path]:
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for path, content in _artefacts().items():
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def stale() -> list[Path]:
    """Committed artefacts that do not match what the models produce now."""
    drifted = []
    for path, content in _artefacts().items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            drifted.append(path)
    return drifted


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit nonzero if the committed files are stale; write nothing",
    )
    args = parser.parse_args()

    if args.check:
        drifted = stale()
        if drifted:
            for path in drifted:
                print(f"STALE: {path.relative_to(REPO_ROOT)}")
            print(f"\nRegenerate with: cd agent && python {Path(GENERATED_BY).name}")
            return 1
        print("up to date")
        return 0

    for path in write():
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
