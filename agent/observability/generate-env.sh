#!/usr/bin/env bash
#
# Generates random secrets for the local Langfuse stack
# (docker-compose.langfuse.yml) and the matching agent-side credentials.
#
# Writes, next to this script, both gitignored and mode 0600:
#   .env                 read automatically by `docker compose` for the
#                        Langfuse stack (database/queue/blob passwords,
#                        NextAuth secret, encryption key, headless-init user
#                        and project API keys)
#   agent-langfuse.env   ONLY the four variables the agent process needs
#                        (app/middleware/logging.py) — so exporting the
#                        agent's config never also exports the stack's
#                        database passwords
#
# Refuses to overwrite existing files: Postgres/ClickHouse/MinIO bake their
# password into the data volume on first boot, so silently regenerating
# secrets against existing volumes produces a stack that cannot start.
# To start over: `docker compose -f docker-compose.langfuse.yml down -v`,
# then rerun with --force.

set -euo pipefail

cd "$(dirname "$0")"

if [[ "${1:-}" != "--force" ]] && { [[ -e .env ]] || [[ -e agent-langfuse.env ]]; }; then
    echo "Refusing to overwrite existing .env / agent-langfuse.env (see header; use --force)." >&2
    exit 1
fi

hex() { openssl rand -hex "$1"; }
uuid() { python3 -c 'import uuid; print(uuid.uuid4())'; }

public_key="pk-lf-$(uuid)"
secret_key="sk-lf-$(uuid)"
user_password="$(hex 16)"

umask 077

cat > .env <<EOF
# Generated by generate-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local development only.
# Never commit. Never reuse these values on a deployed host.
LANGFUSE_WEB_PORT=3000
POSTGRES_PASSWORD=$(hex 24)
CLICKHOUSE_PASSWORD=$(hex 24)
MINIO_ROOT_PASSWORD=$(hex 24)
REDIS_AUTH=$(hex 24)
SALT=$(hex 32)
ENCRYPTION_KEY=$(hex 32)
NEXTAUTH_SECRET=$(hex 32)
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=${public_key}
LANGFUSE_INIT_PROJECT_SECRET_KEY=${secret_key}
LANGFUSE_INIT_USER_EMAIL=admin@clinical-copilot.test
LANGFUSE_INIT_USER_NAME=Local Admin
LANGFUSE_INIT_USER_PASSWORD=${user_password}
EOF

cat > agent-langfuse.env <<EOF
# Agent-side Langfuse export config (app/middleware/logging.py). Local development only.
LANGFUSE_BASE_URL=http://localhost:3000
LANGFUSE_PUBLIC_KEY=${public_key}
LANGFUSE_SECRET_KEY=${secret_key}
LANGFUSE_TRACING_ENVIRONMENT=local-dev
EOF

echo "Wrote $(pwd)/.env and $(pwd)/agent-langfuse.env (mode 0600)."
echo "UI login: admin@clinical-copilot.test / password in .env (LANGFUSE_INIT_USER_PASSWORD)."
