#!/usr/bin/env bash
#
# Generates the PRODUCTION Langfuse secrets, on the Langfuse host, into the
# directory it is run from (/opt/langfuse). Never run it on a laptop and
# copy the result: a secret is generated where it is used (D58).
#
#   ./generate-env-prod.sh <public hostname, e.g. 64-177-51-119.sslip.io>
#
# Writes, mode 0600:
#   .env                 the stack's own passwords, the NextAuth secret and
#                        encryption key, the project API key pair, and the two
#                        UI logins (admin, and the read-only grader viewer
#                        that create-viewer.sh inserts)
#   agent-langfuse.env   ONLY the four variables the agent needs
#                        (app/middleware/logging.py), for the agent host's
#                        /etc/clinical-copilot/agent.env.langfuse-staged
#
# Prints no secret. Refuses to overwrite: Postgres, ClickHouse and MinIO bake
# their passwords into their volumes on first boot (see ../generate-env.sh).

set -euo pipefail

hostname="${1:?usage: generate-env-prod.sh <public hostname>}"
[[ "$hostname" =~ ^[a-z0-9.-]+$ ]] || { echo "not a hostname: $hostname" >&2; exit 2; }

if [[ -e .env || -e agent-langfuse.env ]]; then
    echo "Refusing to overwrite .env / agent-langfuse.env in $(pwd)." >&2
    exit 1
fi

hex() { openssl rand -hex "$1"; }
uuid() { cat /proc/sys/kernel/random/uuid; }

public_key="pk-lf-$(uuid)"
secret_key="sk-lf-$(uuid)"

umask 077

cat > .env <<EOF
# Generated by generate-env-prod.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). PRODUCTION. Never commit.
LANGFUSE_HOSTNAME=${hostname}
POSTGRES_PASSWORD=$(hex 24)
CLICKHOUSE_PASSWORD=$(hex 24)
MINIO_ROOT_PASSWORD=$(hex 24)
REDIS_AUTH=$(hex 24)
SALT=$(hex 32)
ENCRYPTION_KEY=$(hex 32)
NEXTAUTH_SECRET=$(hex 32)
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=${public_key}
LANGFUSE_INIT_PROJECT_SECRET_KEY=${secret_key}
LANGFUSE_INIT_USER_EMAIL=admin@clinical-copilot.test
LANGFUSE_INIT_USER_NAME=Clinical Co-pilot Admin
LANGFUSE_INIT_USER_PASSWORD=$(hex 16)
LANGFUSE_VIEWER_EMAIL=grader@clinical-copilot.test
LANGFUSE_VIEWER_PASSWORD=$(hex 16)
LANGFUSE_RETENTION_DAYS=30
EOF

cat > agent-langfuse.env <<EOF
# Agent-side Langfuse export config (app/middleware/logging.py). PRODUCTION.
LANGFUSE_BASE_URL=https://${hostname}
LANGFUSE_PUBLIC_KEY=${public_key}
LANGFUSE_SECRET_KEY=${secret_key}
LANGFUSE_TRACING_ENVIRONMENT=production
EOF

echo "Wrote $(pwd)/.env and $(pwd)/agent-langfuse.env (mode 0600). No secret printed."
